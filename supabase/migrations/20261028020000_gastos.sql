-- Gastos da loja além das peças (sacolas, papel, etiquetas...). Only adds a table.
-- A purchase in N parcelas counts valor_total / N in each of N months, starting in the month of `data`.
create table if not exists public.gastos (
  id bigint generated by default as identity primary key,
  descricao text not null,
  categoria text,
  valor_total numeric(10,2) not null check (valor_total > 0),
  parcelas int not null default 1 check (parcelas between 1 and 48),
  data date not null,
  created_at timestamptz not null default now()
);
-- No policies: only the server (service role key) reads and writes it.
alter table public.gastos enable row level security;
